"""**2- Graph shows the Annual Returns of Bitcoin**"""

annual = []
for year in sorted(df['Year'].unique()):
    yd = df[df['Year'] == year]
    ret = ((yd['Close'].iloc[-1] - yd['Close'].iloc[0]) / yd['Close'].iloc[0]) * 100
    annual.append({'Year': int(year), 'Return': ret})

annual_df = pd.DataFrame(annual)

plt.figure(figsize=(12, 6))
colors = ['#2ecc71' if r > 0 else '#e74c3c' for r in annual_df['Return']]
bars   = plt.bar(annual_df['Year'].astype(str), annual_df['Return'],
                 color=colors, edgecolor='white', width=0.6)
plt.axhline(0, color='black', linewidth=1.5)

for bar, ret in zip(bars, annual_df['Return']):
    ypos = bar.get_height() + 4 if ret > 0 else bar.get_height() - 18
    plt.text(bar.get_x() + bar.get_width()/2, ypos,
             f'{ret:+.0f}%', ha='center', fontsize=11, fontweight='bold',
             color='#27ae60' if ret > 0 else '#c0392b')

plt.title('Bitcoin Annual Returns (2018–2025)', fontsize=14, fontweight='bold')
plt.xlabel('Year')
plt.ylabel('Return (%)')
plt.grid(True, alpha=0.3, axis='y')
plt.tight_layout()
plt.show()

