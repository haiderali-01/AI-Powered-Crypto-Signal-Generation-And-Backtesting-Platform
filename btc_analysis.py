"""**9- Graph shows the Volatility Regime vs Signal Reliability**"""

df['Vol_Regime'] = pd.cut(df['Volatility_7'], bins=3,
                           labels=['Low', 'Medium', 'High'])

regime = df.groupby('Vol_Regime', observed=True).agg(
    UP_pct   = ('Label', 'mean'),
    Total    = ('Label', 'count')
).reset_index()
regime['UP_pct']   *= 100
regime['DOWN_pct']  = 100 - regime['UP_pct']

fig, ax = plt.subplots(figsize=(12, 6))
y_pos   = [2, 1, 0]
height  = 0.35
colors_r = ['#3498db', '#f39c12', '#e74c3c']

for i, row in regime.iterrows():
    ax.barh(y_pos[i] + height/2, row['UP_pct'],
            height=height, color='#2ecc71', edgecolor='white')
    ax.barh(y_pos[i] - height/2, row['DOWN_pct'],
            height=height, color='#e74c3c', edgecolor='white')
    ax.text(row['UP_pct']/2,   y_pos[i] + height/2,
            f"UP: {row['UP_pct']:.1f}%",
            ha='center', va='center', fontsize=12,
            fontweight='bold', color='white')
    ax.text(row['DOWN_pct']/2, y_pos[i] - height/2,
            f"DOWN: {row['DOWN_pct']:.1f}%",
            ha='center', va='center', fontsize=12,
            fontweight='bold', color='white')
    ax.text(102, y_pos[i], f"n={int(row['Total'])}",
            va='center', fontsize=11, fontweight='bold')
    ax.text(-1, y_pos[i], f"{row['Vol_Regime']} Volatility",
            ha='right', va='center', fontsize=12,
            fontweight='bold', color=colors_r[i])

ax.axvline(51.2, color='black', linestyle='--', linewidth=2)
ax.set_xlim(0, 100)
ax.set_ylim(-0.6, 2.8)
ax.set_yticks([])
ax.set_xlabel('Percentage (%)', fontsize=12)
ax.grid(True, alpha=0.3, axis='x')

patches = [mpatches.Patch(color='#2ecc71', label='UP Days'),
           mpatches.Patch(color='#e74c3c', label='DOWN Days'),
           plt.Line2D([0],[0], color='black', linestyle='--', label='Avg (51.2%)')]
ax.legend(handles=patches, fontsize=11, loc='lower right')
ax.set_title('Volatility Regime vs Signal Reliability', fontsize=14, fontweight='bold')

plt.tight_layout()
plt.show()

